import glob as _glob
import json as _json

_D21 = RES / "ref" / "single21"
S21 = {}
for _f in _glob.glob(str(_D21 / "surv_part*.json")):
    S21.update(_json.load(open(_f, encoding="utf-8")))
T21 = _json.load(open(_D21 / "tdauc_21.json", encoding="utf-8"))
_MODELS = ("dyam", "ovo", "dyam_nlp", "ovo_nlp")


def _row(c, getter, fmt):
    v = S21[c]
    labs = c.endswith("+Labs")
    vals = [getter(v, m if (labs or m in v) and m in v else m.replace("_nlp", "")) for m in _MODELS]
    mx = max(round(x, 3) for x in (vals if labs else vals[:2]))
    return [(r"\textbf{%s}" % fmt(x)) if round(x, 3) == mx and (labs or j < 2) else fmt(x) for j, x in enumerate(vals)]


