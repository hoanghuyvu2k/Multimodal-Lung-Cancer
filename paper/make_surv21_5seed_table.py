"""Hai bang song con 21 to hop, 5 seed x 10-fold (ref-linux-py38), tu experiments/results/ref/multi21.
Ra paper/tables/table_surv21_5seed.tex (2 bang: (a) C-index + log HR, (b) log-rank chi2 + tdAUC 12 thang, nhu paper_1seed)
va paper/word_export/surv21_5seed_rows.json ({"a": [...], "b": [...]}) cho ban Word.   python paper/make_surv21_5seed_table.py"""
import glob
import json
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent
D = HERE.parent / "experiments" / "results" / "ref" / "multi21"
R = {}
for f in glob.glob(str(D / "surv_part*.json")):
    R.update(json.load(open(f, encoding="utf-8")))
T = json.load(open(D / "tdauc_21_5seed.json", encoding="utf-8"))
BM = {"PDL1+Gen": "BM4", "Rad+Gen": "BM3", "Rad+IHC-G+Gen+PDL1": "BM1", "Rad+IHC-G+Gen+PDL1+Labs": "BM2"}
K = {"TMB": 1, "PDL1": 1, "IHC-A": 1, "Gen": 1, "Rad": 3, "Rad-LU": 4, "TMB+PDL1": 2, "PDL1+Gen": 2, "Rad+IHC-A": 4,
     "Rad+IHC-G": 4, "Rad+Gen": 4, "IHC-A+Gen": 2, "IHC-G+Gen": 2, "Rad+IHC-A+Gen": 5, "Rad+IHC-G+Gen": 5,
     "Rad+IHC-A+MutAmp": 6, "Rad+IHC-A+Gen+PDL1": 6, "Rad+IHC-G+Gen+PDL1": 6, "Rad+IHC-A+Gen+TMB+PDL1": 7,
     "Rad+IHC-A+Gen+PDL1+Labs": 7, "Rad+IHC-G+Gen+PDL1+Labs": 7}
MODELS = ("dyam", "ovo", "dyam_nlp", "ovo_nlp")
B = chr(92)

METRICS = {
    "cindex": (lambda v, i, m: np.mean(v[m]["cindex"]), 3),
    "loghr": (lambda v, i, m: np.mean(v[m]["loghr"]), 3),
    "chi2": (lambda v, i, m: np.mean(v[m]["km"]), 1),
    "td12": (lambda v, i, m: np.mean(T[f"{i:02d}__{m}"]["12"]), 3),
}


def cells(v, i, labs, key):
    g, dec = METRICS[key]
    vals = [g(v, i, m if m in v else m.replace("_nlp", "")) for m in MODELS]
    mx = max(round(x, dec) for x in (vals if labs else vals[:2]))
    return [(B + "textbf{%.*f}" % (dec, x)) if round(x, dec) == mx and (labs or j < 2) else "%.*f" % (dec, x)
            for j, x in enumerate(vals)]


def build(keys):
    rows, word = [], []
    for c, v in sorted(R.items(), key=lambda kv: kv[1]["idx"]):
        i = v["idx"]; labs = c.endswith("+Labs")
        cl = sum((cells(v, i, labs, k) for k in keys), [])
        name = c + (f" ({BM[c]})" if c in BM else "")
        rows.append(f"{i:<2} & {name:<30} & {K[c]} & " + " & ".join(cl) + " " + B + B)
        word.append([str(i), name, str(K[c])] + [x.replace(B + "textbf{", "").replace("}", "") for x in cl])
    return rows, word


def table(rows, caption, label, head1, head2):
    return ("\\begin{table}[H]\n\\centering\n\\caption{" + caption + "}\n\\label{" + label + "}\n\\scriptsize\n\\setlength{\\tabcolsep}{2pt}\n"
            "\\begin{tabular}{@{}rlc" + "cccc" * 2 + "@{}}\n\\toprule\n"
            " & & & \\multicolumn{4}{c}{" + head1 + "} & \\multicolumn{4}{c}{" + head2 + "} \\\\\n"
            "\\cmidrule(lr){4-7} \\cmidrule(lr){8-11}\n"
            "\\# & Configuration & $k$ & " + " & ".join(["DyAM & OvO & DyAM+NLP & OvO+NLP"] * 2) + " \\\\\n\\midrule\n"
            + "\n".join(rows) + "\n\\bottomrule\n\\end{tabular}\n\\end{table}\n")


COMMON = ("5~seeds~$\\times$~10-fold, each value the mean over the 5 seeds ($n = 247$; 209 events, median PFS 2.7~months), the same models and partitions as "
          "Table~\\ref{tab:ovo_all21}. As there, the NLP encoding replaces the numeric labs, so only configurations 20 and 21 differ between the models with and "
          "without NLP; the +NLP entries of the other configurations repeat the values without NLP (not in bold). For $k = 1$ OvO reduces to the cooperative "
          "formulation. Bold marks the highest value in each row and metric.")
capA = ("Progression-free survival association of the fused risk score across the 21 configurations: Harrell's C-index and the log hazard ratio per 1~s.d. of the "
        "risk score (adjusted for age, ECOG, albumin, dNLR and liver metastases). " + COMMON)
capB = ("Kaplan--Meier log-rank statistic (patients dichotomised at the median risk score; $\\chi^2 > 3.84$ corresponds to $p < 0.05$) and cumulative/dynamic "
        "time-dependent AUC at 12 months (Uno estimator) across the 21 configurations. " + COMMON)

rowsA, wordA = build(("cindex", "loghr"))
rowsB, wordB = build(("chi2", "td12"))
tex = ("%% tables/table_surv21_5seed.tex (GENERATED by paper/make_surv21_5seed_table.py - do not edit by hand)\n"
       + table(rowsA, capA, "tab:surv21", "C-index", "log HR") + "\n" + table(rowsB, capB, "tab:surv21b", "Log-rank $\\chi^2$", "tdAUC 12~mo"))
(HERE / "tables" / "table_surv21_5seed.tex").write_text(tex, encoding="utf-8")
(HERE / "word_export" / "surv21_5seed_rows.json").write_text(json.dumps({"a": wordA, "b": wordB}, ensure_ascii=False), encoding="utf-8")
print("ok", len(rowsA), len(rowsB))
