NLP20 = [("Rad+IHC-A+Gen", "Rad_IHCA_Gen"), ("Rad+IHC-G+Gen", "Rad_IHCG_Gen"), ("Rad+IHC-A+MutAmp", "Rad_IHCA_MutAmp"),
         ("Rad+IHC-A+Gen+PDL1", "Rad_IHCA_Gen_PDL1"), ("Rad+IHC-G+Gen+PDL1 (BM1)", "Rad_IHCG_Gen_PDL1"),
         ("Rad+IHC-A+Gen+TMB+PDL1", "Rad_IHCA_Gen_TMB_PDL1")]


FIVE = ["seed_%d" % x for x in (42, 7, 123, 2024, 31337)]   # the 5 standard seeds (first five columns of the 20-seed files)


def table_nlp20():
    import pandas as pd
    from sklearn.metrics import roc_auc_score
    rng = np.random.default_rng(0)
    O = SRC / "ovo_proof"

    def cols(df):
        return [c for c in df.columns if c in FIVE]

    def per(df):
        return np.array([roc_auc_score(df.loc[df[c].notna(), "label"], df.loc[df[c].notna(), c]) for c in cols(df)])

    def ens(df):
        c = cols(df)
        return ((df[c] - df[c].mean()) / df[c].std()).mean(axis=1)

    lines, stats = [], []
    for name, sl in NLP20:
        d = pd.read_csv(O / f"nlp20_dyam__{sl}.csv", index_col=0)
        o = pd.read_csv(O / f"nlp20_ovo__{sl}.csv", index_col=0)
        a, b = per(d), per(o)
        ed, eo = ens(d), ens(o)
        k = (ed.notna() & eo.notna()).values
        y = d["label"].values[k]
        ed, eo = ed.values[k], eo.values[k]
        ad, ao = roc_auc_score(y, ed), roc_auc_score(y, eo)
        bs = []
        for _ in range(5000):
            i = rng.integers(0, k.sum(), k.sum())
            if len(set(y[i])) == 2:
                bs.append(roc_auc_score(y[i], eo[i]) - roc_auc_score(y[i], ed[i]))
        lo, hi = np.percentile(bs, [2.5, 97.5])
        stats.append((a.mean(), b.mean(), ad, ao, (b - a).mean(), int((b > a).sum())))
        lines.append(f"{name} & {a.mean():.3f} ({a.std(ddof=1):.3f}) & {b.mean():.3f} ({b.std(ddof=1):.3f}) & "
                     f"${(b - a).mean():+.3f}$ ({int((b > a).sum())}/5) & {ad:.3f} & {ao:.3f} & ${ao - ad:+.3f}$ [${lo:+.3f}$, ${hi:+.3f}$] \\\\")
    st = np.array(stats)
    return NLP20_TMPL.replace("@@BODY@@", "\n".join(lines)), st



