def load21_ref():
    R = {}
    for f in sorted(glob.glob(str(RES / "ref_all21_part*.json"))):
        R.update(json.load(open(f, encoding="utf-8")))
    return [(i, label, K[label], R[label]["dyam"]["mean"], R[label]["ovo"]["mean"], R[label]["dyam_nlp"]["mean"], R[label]["ovo_nlp"]["mean"])
            for i, label in enumerate(K, 1)]


def load21():
    if REFMODE:
        return load21_ref()
    d = {}
    for f in glob.glob(str(RES / "dyam_nlp_combos_part*.json")):
        d.update(json.load(open(f, encoding="utf-8")))
    o = json.load(open(RES / "ovo_nlp_combos.json", encoding="utf-8"))["combos"]
    lab = json.load(open(RES / "dyam_ovo_labs21.json", encoding="utf-8"))
    rows = []
    for i, label in enumerate(o, 1):
        a0, b0 = d[label]["base"]["mean"], o[label]["base"]["mean"]
        if label.endswith("+Labs"):
            a0, b0 = lab[f"{label}|dyam"]["mean"], lab[f"{label}|ovo"]["mean"]
        rows.append((i, label, K[label], a0, b0, d[label]["nlp"]["mean"], o[label]["nlp"]["mean"]))
    return rows


