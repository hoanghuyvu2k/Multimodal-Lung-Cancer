def summary(rows):
    R = np.array([[r[3], r[4], r[5], r[6]] for r in rows])
    k = np.array([r[2] for r in rows])
    e = 1e-9
    s = {"ovo_gt_dyam": int((R[:, 1] > R[:, 0] + e).sum()), "ovo_lt_dyam": int((R[:, 1] < R[:, 0] - e).sum()),
         "ovoN_gt_dyamN": int((R[:, 3] > R[:, 2] + e).sum()), "ovoN_lt_dyamN": int((R[:, 3] < R[:, 2] - e).sum())}
    m5 = k >= 5
    d5, d5n = R[m5, 1] - R[m5, 0], R[m5, 3] - R[m5, 2]
    s.update(k5_n=int(m5.sum()), k5_ovo_ge=int((d5 >= -e).sum()), k5_d=float(d5.mean()), k5_rng=(float(d5.min()), float(d5.max())),
             k5_ovoN_ge=int((d5n >= -e).sum()), k5_dN=float(d5n.mean()), k5_rngN=(float(d5n.min()), float(d5n.max())),
             k24_ovo_gt=int((R[~m5, 1] > R[~m5, 0] + e).sum()), k24_n=int((~m5).sum()),
             best=[float(R[:, j].max()) for j in range(4)],
             nlp_improves_dyam=int((R[:, 2] > R[:, 0]).sum()), nlp_improves_ovo=int((R[:, 3] > R[:, 1]).sum()))
    return s


