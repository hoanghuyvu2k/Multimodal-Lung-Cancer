def table21(rows):
    lines = []
    for i, label, k, a, b, an, bn in rows:
        labs = label.endswith("+Labs")
        if not labs:
            an, bn = a, b
        vals = [a, b, an, bn]
        m = max(round(v, 3) for v in (vals if labs else vals[:2]))
        cells = [f"\\textbf{{{f3(v)}}}" if round(v, 3) == m and (labs or j < 2) else f3(v) for j, v in enumerate(vals)]
        name = label + (f" ({BM[label]})" if label in BM else "")
        lines.append(f"{i:<2} & {name:<32} & {k} & " + " & ".join(cells) + " \\\\")
    return TABLE21.replace("@@BODY@@", "\n".join(lines))


def ms(x, d=3):
    return f"{x['mean']:.{d}f} $\\pm$ {x['sd']:.{d}f}"


