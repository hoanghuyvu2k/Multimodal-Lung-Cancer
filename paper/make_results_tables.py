def table_loso():
    import pandas as pd
    from sklearn.metrics import roc_auc_score
    O = SRC / "ovo_proof"

    def per(df):
        return {c: roc_auc_score(df.loc[df[c].notna(), "label"], df.loc[df[c].notna(), c]) for c in df.columns if c in FIVE}

    ref = per(pd.read_csv(O / "nlp20_ovo__Rad_IHCG_Gen_PDL1.csv", index_col=0))
    names = [("path", "Pathology IHC-G"), ("rad", "CT radiomics (3 sites)"), ("pdl1", "PD-L1 TPS"),
             ("nlp", "NLP-encoded clinical"), ("gen", "Genomics")]
    rows = []
    for a, nm in names:
        p = per(pd.read_csv(O / f"loso_ovo_{a}.csv", index_col=0))
        d = np.array([p[k] - ref[k] for k in p])
        rows.append(f"{nm} & {np.mean(list(p.values())):.3f} & ${d.mean():+.3f}$ & {int((d < 0).sum())}/5 \\\\")
    return LOSO_TMPL.replace("@@FULL@@", f"{np.mean(list(ref.values())):.3f}").replace("@@BODY@@", "\n".join(rows))


