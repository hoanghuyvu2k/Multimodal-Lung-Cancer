def nlp_tables(five):
    out = {}
    for arm, tag, fname in (("IHC-A", "ihca", "table2_auc_ihca"), ("IHC-G", "ihcg", "table3_auc_ihcg")):
        A = five["arms"][arm]
        rows = []
        for v, x in A.items():
            a = x["auc"]["mean"]
            dn_s = "(ref)" if v == "No clinical" else f"${a - A['No clinical']['auc']['mean']:+.3f}$"
            dl = "n/a" if v in ("No clinical", "+ Labs") else f"${a - A['+ Labs']['auc']['mean']:+.3f}$"
            rows.append(f"{NAMES[v]:<30} & {ms(x['auc'])} & {dn_s} & {dl} \\\\")
        out[fname] = (AUC_TMPL.replace("@@FILE@@", fname).replace("@@ARM@@", arm)
                      .replace("@@TAG@@", tag).replace("@@BODY@@", "\n".join(rows)))
    srows, krows = [], []
    td = json.load(open(SRC / "tdauc_5seed.json", encoding="utf-8"))
    stem = {"No clinical": "no_clinical", "+ Labs": "labs", "+ NLP raw": "nlp_raw", "+ NLP-PCA16": "nlppca16",
            "+ Labs + NLP": "labs__nlp", "+ Labs + NLP-PCA16": "labs__nlppca16", "+ BioClinBERT-PCA16": "bioclinbertpca16"}
    for arm in ("IHC-A", "IHC-G"):
        srows.append(f"\\multicolumn{{6}}{{l}}{{\\textit{{{arm} arm}}}} \\\\")
        for v, x in five["arms"][arm].items():
            t = td[f"{arm}__{stem[v]}"]
            tcell = " & ".join(f"{t[k]['mean']:.3f} $\\pm$ {t[k]['sd']:.3f}" for k in ("6", "12", "18"))
            srows.append(f"{NAMES[v]:<30} & {ms(x['cindex'])} & {x['cox_hr']['mean']:.2f} $\\pm$ {x['cox_hr']['sd']:.2f} & {tcell} \\\\")
            krows.append(f"{NAMES[v]:<30} & {arm} & {x['km_chi2']['mean']:.1f} $\\pm$ {x['km_chi2']['sd']:.1f} & {min(x['km_chi2']['per_seed']):.1f} \\\\")
        if arm == "IHC-A":
            srows.append("\\midrule")
    out["table4_survival"] = SURV_TMPL.replace("@@BODY@@", "\n".join(srows))
    out["table5_km"] = KM_TMPL.replace("@@BODY@@", "\n".join(krows))
    return out


